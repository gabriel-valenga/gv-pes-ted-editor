"""
Calculated player attributes.

These values are generated by PES GV and are NOT original
fields stored in the PES 2021 TED file.
"""

from editing.players.overall import calculate_overall


def calculate_bmi(player):
    """
    Calculate the player's BMI using weight (kg) and height (cm).

    Returns:
        float: BMI rounded to one decimal place.
        None: If weight or height is missing or invalid.
    """
    weight = player.get("weight")
    height = player.get("height")

    if isinstance(weight, bool) or isinstance(height, bool):
        return None

    if not isinstance(weight, (int, float)):
        return None

    if not isinstance(height, (int, float)):
        return None

    if weight <= 0 or height <= 0:
        return None

    height_meters = height / 100

    bmi = weight / (height_meters ** 2)

    return round(bmi, 1)


def calculate_player_attributes(player):
    """
    Return calculated attributes for a player.

    These attributes are virtual: they are not part of the
    original TED data and must never be written to the TED file.
    """
    return {
        "bmi": calculate_bmi(player),
        "overall": calculate_overall(player),
    }